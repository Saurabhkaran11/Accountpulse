def _load_settings():
    """
    Read keys from backend/.env and the project-wide KEYS.env.
    Priority: real environment variables > non-empty backend/.env > KEYS.env.
    Empty values never hide a key filled in elsewhere.
    """
    from pathlib import Path
    from dotenv import dotenv_values
    here = Path(__file__).resolve().parent
    merged = {k: v for k, v in dotenv_values(here.parent / "KEYS.env").items() if v}
    merged.update({k: v for k, v in dotenv_values(here / ".env").items() if v})
    for k, v in merged.items():
        if not os.environ.get(k):
            os.environ[k] = v


_load_settings()

env = os.getenv
MOCK = env("MOCK", "true").lower() == "true"

# ---------- LLM clients (both speak the OpenAI API format) ----------
crusoe = OpenAI(api_key=env("CRUSOE_API_KEY", "x"),
                base_url=env("CRUSOE_BASE_URL", "https://api.inference.crusoecloud.com/v1"))
CRUSOE_MODEL = env("CRUSOE_MODEL", "meta-llama/Llama-3.3-70B-Instruct")

openrouter = OpenAI(api_key=env("OPENROUTER_API_KEY", "x"), base_url="https://openrouter.ai/api/v1")
# Model/provider pairings verified end to end in DuploCloud's hackday guide
# (github.com/duplocloud/devkit/tree/main/hackday, "Sponsor Integrations.md").
CRITIC_MODEL = env("CRITIC_MODEL", "z-ai/glm-5.1")                          # on Nebius
CRUSOE_OR_MODEL = env("CRUSOE_VIA_OPENROUTER_MODEL", "z-ai/glm-5.3")        # on Crusoe


def _pinned(provider):
    """OpenRouter routing that only allows one provider, with no silent fallback."""
    return {"provider": {"only": [provider], "allow_fallbacks": False}}


def _served_by(out, default):
    """OpenRouter returns the provider that actually answered in a top-level 'provider' field."""
    return getattr(out, "provider", None) or (getattr(out, "model_extra", None) or {}).get("provider") or default


def crusoe_route():
    """direct = Crusoe API key; openrouter = OpenRouter pinned to Crusoe; mock = neither."""
    if MOCK:
        return "mock"
    if env("CRUSOE_API_KEY"):
        return "direct"
    if env("OPENROUTER_API_KEY"):
        return "openrouter"
    return "mock"


def crusoe_chat(messages, **kw):
    """Run a prompt on Crusoe GPUs. Returns (text, provider label) or (None, "mock")."""
    route = crusoe_route()
    if route == "direct":
        out = crusoe.chat.completions.create(model=CRUSOE_MODEL, messages=messages, **kw)
        label = f"crusoe:{CRUSOE_MODEL}"
    elif route == "openrouter":
        out = openrouter.chat.completions.create(model=CRUSOE_OR_MODEL, messages=messages,
                                                 extra_body=_pinned("crusoe"), **kw)
        label = f"crusoe-via-openrouter:{CRUSOE_OR_MODEL} served_by={_served_by(out, 'crusoe')}"
    else:
        return None, "mock"
    print(f"[LLM] provider={label}")  # visible proof for judges
    return out.choices[0].message.content, label


def _safe(name, real, fallback):
    """Call a sponsor; if it errors mid-demo, log it and use sample data instead of crashing."""
    try:
        return real()
    except Exception as e:  # noqa: BLE001 - any failure should degrade, not crash the demo
        print(f"[WARN] {name} failed ({type(e).__name__}: {str(e)[:120]}); using sample data")
        return fallback()

