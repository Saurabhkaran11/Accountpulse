def _json_from(text: str) -> dict:
    """LLMs sometimes wrap JSON in prose; take the outermost {...} block."""
    return json.loads(text[text.find("{"): text.rfind("}") + 1])


# ---------- 1. Merge.dev: accounts + tickets ----------
