"""
AccountPulse agent API (FastAPI).

Finds customer revenue at risk before renewal. Each step uses one sponsor
tool that does real work in the pipeline:

  1. Merge.dev   -> customer accounts + tickets from any CRM / help desk
  2. Brave       -> fresh news about each customer (layoffs, funding, M&A)
                    (no key? free Google News RSS is used instead)
  3. Similarweb  -> competitor website-traffic momentum
  4. Crusoe      -> LLM reasoning: risk score, reasons, next step
                    (direct API key, or OpenRouter pinned to Crusoe)
  5. OpenRouter  -> independent critic model (routed to Nebius) that can veto
  6. Neo4j       -> knowledge graph: Account -> Signal -> Competitor

Every external call has a MOCK fallback, so the API always answers, even
before any keys are added.

Run:   uvicorn app:app --reload --port 8000
Docs:  http://localhost:8000/docs  (interactive, auto-generated by FastAPI)
"""
