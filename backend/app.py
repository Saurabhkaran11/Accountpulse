@app.get("/scan")
def scan():
    """Run the full pipeline over every account and return raw results sorted by risk."""
    results = []
    mock_accounts = lambda: [{"name": "Acme Logistics", "domain": "acmelogistics.com", "arr": 120000,  # noqa: E731
                              "competitor": "routewise.com", "open_tickets": 7}]
    for acc in _safe("Merge.dev", get_accounts, mock_accounts):
        # On a live-mode failure, use no news rather than invented headlines.
        news = _safe("News", lambda: brave_news(acc["name"]), lambda: [])
        mom = _safe("Similarweb", lambda: competitor_momentum(acc["competitor"]),
                    lambda: {"domain": acc["competitor"], "visits_change_pct": None})
        verdict = _safe("Crusoe", lambda: analyze(acc, news, mom),
                        lambda: {"risk_score": 50, "reasons": ["AI scoring unavailable; showing a neutral score"],
                                 "play": "Review this account manually", "provider": "mock (Crusoe call failed)"})
        review = _safe("OpenRouter/Nebius critic", lambda: critic(acc, verdict, news, mom),
                       lambda: {"approve": True, "note": "Critic unavailable; not checked."})
        if not review.get("approve", True):
            verdict["risk_score"] = min(verdict["risk_score"], 50)
            verdict["reasons"].append(f"Critic veto: {review.get('note')}")
        _safe("Neo4j", lambda: save_graph(acc, news, mom, verdict), lambda: None)
        results.append({"account": acc, "news": news, "competitor": mom, "verdict": verdict, "critic": review})
        _history.setdefault(_slug(acc["name"]), []).append(int(verdict["risk_score"]))
    results.sort(key=lambda r: r["verdict"]["risk_score"], reverse=True)
    payload = {"revenue_at_risk": sum(r["account"]["arr"] for r in results if r["verdict"]["risk_score"] >= 70),
               "accounts": results}
    _last_scan.clear()
    _last_scan.update(payload)
    _last_scan_at[:] = [datetime.now(timezone.utc).isoformat(timespec="seconds")]
    return payload


@app.get("/accounts")
def accounts():
    """What the dashboard shows: latest scan in the web app's Account format (scans once if needed)."""
    return accounts_payload()


@app.get("/accounts/{account_id}")
def account(account_id: str):
    for a in accounts_payload()["accounts"]:
        if a["id"] == account_id:
            return a
    from fastapi import HTTPException
    raise HTTPException(404, f"No account '{account_id}'")


@app.post("/scan")
def rescan():
    """The dashboard's Run scan button: fresh scan, returned in the dashboard format."""
    scan()
    return accounts_payload()


class AskIn(BaseModel):
    question: str


@app.post("/ask")
def ask(body: AskIn):
    """
    Answer a plain-English question about the book of accounts.
    Contract used by the front end (lib/ai.ts): {answer, accounts, engine}.
    Next step: turn the question into Neo4j Cypher and answer from the results.
    """
    if not _last_scan:
        scan()
    ui = [to_ui_account(r) for r in _last_scan["accounts"]]
    top = ui[0]
    demo = {"answer": f"Start with {top['name']}: risk {top['risk']}. Next step: {top['play']}",
            "accounts": [top], "engine": "demo"}
    compact = [{k: a[k] for k in ("name", "risk", "arr", "renewalDate", "openTickets", "why", "play")} for a in ui]
    messages = [{"role": "system", "content": "You help a customer-success manager. Answer in 2-3 plain sentences "
                                              "using only the account data given. Name the accounts you mean."},
                {"role": "user", "content": f"Accounts: {json.dumps(compact)}\nQuestion: {body.question}"}]
    # Reasoning models (e.g. gpt-oss) spend tokens thinking first, so leave room for the answer.
    text, _ = _safe("Crusoe", lambda: crusoe_chat(messages, temperature=0.2, max_tokens=1200), lambda: (None, "mock"))
    if not text:
        return demo
    mentioned = [a for a in ui if a["name"].lower() in text.lower()] or [top]
    return {"answer": text.strip(), "accounts": mentioned, "engine": "crusoe"}
